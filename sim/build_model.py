"""Generate sim/assets/rover.xml from sim/params.py, so every physical number in the MJCF has a sourced origin.

    .venv/Scripts/python -m sim.build_model
"""
from __future__ import annotations

import pathlib

from . import params as P

OUT = pathlib.Path(__file__).resolve().parent / "assets" / "rover.xml"

# field layout (shared with rover_env)
ROW_YS = [-3.0, -1.5, 0.0, 1.5, 3.0]
ROW_X0, ROW_X1 = 1.0, 7.0
ROW_HALF_W = 0.15
ROW_H = 0.25
HF_NROW, HF_NCOL = 97, 129          # rows along y, cols along x
HF_SIZE = (8.0, 6.0, 0.10, 0.05)    # half x, half y, max elevation, base depth
HF_POS = (2.0, 0.0)


def build() -> str:
    r, ww = P.WHEEL_RADIUS, P.WHEEL_WIDTH
    hx, hy = P.WHEELBASE / 2, P.TRACK / 2
    deck_z = P.RIDE_Z
    mast_x, mast_y = -0.10, P.DECK_W / 2 - 0.02
    wheels = []
    for name, x, y in (("fl", hx, hy), ("fr", hx, -hy), ("rl", -hx, hy), ("rr", -hx, -hy)):
        wheels.append(f"""
      <body name="wheel_{name}" pos="{x} {y} 0">
        <joint name="wheel_{name}" type="hinge" axis="0 1 0" damping="0.01" armature="0.002"/>
        <geom name="tyre_{name}" type="sphere" size="{r}" mass="{P.WHEEL_MASS}" rgba="0.12 0.12 0.12 1"
              contype="4" conaffinity="1" friction="0.8 0.01 0.001" condim="4" group="3"/>
        <geom type="cylinder" size="{r} {ww/2}" euler="90 0 0" contype="0" conaffinity="0" mass="0"
              rgba="0.15 0.15 0.15 1"/>
        <geom type="cylinder" size="{r*0.45} {ww/2+0.002}" euler="90 0 0" contype="0" conaffinity="0" mass="0"
              rgba="0.7 0.7 0.72 1"/>
      </body>""")
    motors = "\n".join(
        f'    <general name="m_{n}" joint="wheel_{n}" ctrlrange="-1 1" gainprm="{P.STALL_TORQUE}" biastype="affine" '
        f'biasprm="0 0 {-P.STALL_TORQUE / P.NO_LOAD_SPEED:.5f}" forcerange="{-P.STALL_TORQUE} {P.STALL_TORQUE}"/>'
        for n in ("fl", "fr", "rl", "rr"))
    # cloth: chain of hinged panels hanging from the boom tip
    panels = ""
    for i in reversed(range(P.N_PANELS)):
        pm = P.M_COVER_CLOTH / P.N_PANELS
        inner = panels
        z0 = 0 if i == 0 else -P.PANEL_LEN
        panels = f"""
            <body name="cover_{i}" pos="0 0 {z0}">
              <joint name="cloth_{i}" type="hinge" axis="1 0 0" damping="0.15" range="-150 150"/>
              <geom name="panel_{i}" type="box" size="{P.PANEL_W/2} 0.004 {P.PANEL_LEN/2}" pos="0 0 {-P.PANEL_LEN/2}"
                    mass="{pm}" rgba="0.92 0.93 0.95 0.9" contype="2" conaffinity="1" friction="0.6 0.005 0.0001"/>{inner}
            </body>"""
    rows = []
    for k, y in enumerate(ROW_YS):
        rows.append(f'    <geom name="row_{k}" type="box" pos="{(ROW_X0+ROW_X1)/2} {y} {ROW_H/2}" '
                    f'size="{(ROW_X1-ROW_X0)/2} {ROW_HALF_W} {ROW_H/2}" rgba="0.18 0.42 0.16 1" contype="2" conaffinity="2"/>')
        for j in range(14):
            x = ROW_X0 + 0.2 + j * (ROW_X1 - ROW_X0 - 0.4) / 13
            rows.append(f'    <geom type="sphere" pos="{x:.2f} {y} {ROW_H}" size="0.16" rgba="0.25 0.55 0.2 1" '
                        f'contype="0" conaffinity="0"/>')
    hx_, hy_, hz_, hb_ = HF_SIZE
    return f"""<mujoco model="frost_guard_rover">
  <!-- GENERATED by sim/build_model.py from sim/params.py; edit params, not this file. -->
  <compiler angle="degree" autolimits="true"/>
  <option timestep="{P.SIM_DT}" integrator="implicitfast" cone="pyramidal"/>
  <visual>
    <global offwidth="960" offheight="544"/>
    <quality shadowsize="2048"/>
    <headlight ambient="0.35 0.35 0.4" diffuse="0.5 0.5 0.5"/>
  </visual>
  <asset>
    <texture name="sky" type="skybox" builtin="gradient" rgb1="0.10 0.12 0.25" rgb2="0.02 0.02 0.06" width="256" height="256"/>
    <texture name="soil" type="2d" builtin="checker" rgb1="0.33 0.25 0.17" rgb2="0.30 0.22 0.15" width="256" height="256"/>
    <material name="soil" texture="soil" texrepeat="24 18"/>
    <hfield name="terrain" nrow="{HF_NROW}" ncol="{HF_NCOL}" size="{hx_} {hy_} {hz_} {hb_}"/>
  </asset>
  <worldbody>
    <light pos="2 -3 6" dir="0 0.4 -1" diffuse="0.6 0.6 0.7" castshadow="true"/>
    <geom name="ground" type="hfield" hfield="terrain" pos="{HF_POS[0]} {HF_POS[1]} 0" material="soil"
          contype="1" conaffinity="1" friction="0.8 0.01 0.001"/>
{chr(10).join(rows)}
    <body name="station" mocap="true" pos="3 0.6 0">
      <geom type="cylinder" size="0.12 0.005" rgba="1 0.55 0.1 0.8" contype="0" conaffinity="0"/>
      <geom type="box" size="0.01 0.01 0.25" pos="0 0 0.25" rgba="1 0.55 0.1 1" contype="0" conaffinity="0"/>
      <geom type="box" size="0.12 0.005 0.005" pos="0.12 0 0.01" rgba="1 0.9 0.2 1" contype="0" conaffinity="0"/>
    </body>

    <body name="chassis" pos="0 0 {r + 0.02}">
      <freejoint name="root"/>
      <site name="imu" pos="0 0 {deck_z}"/>
      <geom name="deck" type="box" size="{P.DECK_L/2} {P.DECK_W/2} {P.DECK_T/2 + 0.01}" pos="0 0 {deck_z}"
            mass="{P.M_DECK + P.M_RAILS}" rgba="0.55 0.57 0.6 1" contype="4" conaffinity="1"/>
      <geom name="battery" type="box" size="0.09 0.05 0.04" pos="0.05 -0.05 {deck_z + 0.05}" mass="{P.M_BATTERY}"
            rgba="0.15 0.3 0.6 1" contype="0" conaffinity="0"/>
      <geom name="enclosure" type="box" size="0.10 0.06 0.0375" pos="0.16 0.08 {deck_z + 0.048}" mass="{P.M_ENCLOSURE}"
            rgba="0.8 0.8 0.78 1" contype="0" conaffinity="0"/>
      <geom name="motors" type="box" size="{hx} 0.12 0.02" pos="0 0 {-0.005}" mass="{4 * P.MOTOR_MASS}"
            rgba="0.3 0.3 0.32 1" contype="0" conaffinity="0"/>
      <geom name="mast" type="box" size="0.01 0.01 {P.MAST_H/2}" pos="{mast_x} {mast_y} {deck_z + P.MAST_H/2}"
            mass="{P.M_MAST}" rgba="0.6 0.62 0.65 1" contype="0" conaffinity="0"/>
      <geom name="shield" type="cylinder" size="0.06 0.05" pos="{mast_x + 0.06} {mast_y} {deck_z + P.MAST_H*0.7}"
            mass="{P.M_SHIELD}" rgba="0.95 0.95 0.95 1" contype="0" conaffinity="0"/>
      <geom name="gnss" type="cylinder" size="0.04 0.01" pos="{mast_x} {mast_y} {deck_z + P.MAST_H + 0.01}"
            mass="{P.M_GNSS}" rgba="0.1 0.1 0.1 1" contype="0" conaffinity="0"/>
      <geom name="actuator" type="capsule" fromto="{mast_x} {mast_y - 0.02} {deck_z + 0.5} {mast_x} {mast_y - 0.02} {deck_z + 0.72}"
            size="0.012" mass="{P.M_ACTUATOR}" rgba="0.2 0.2 0.2 1" contype="0" conaffinity="0"/>
      <site name="gnss" pos="{mast_x} {mast_y} {deck_z + P.MAST_H + 0.02}"/>
      <body name="boom" pos="{mast_x} {mast_y} {deck_z + P.MAST_H}">
        <joint name="boom" type="hinge" axis="-1 0 0" range="0 95" damping="0.5" stiffness="{P.BOOM_SPRING}" springref="0"/>
        <geom name="boom" type="box" size="0.01 0.01 {P.BOOM_LEN/2}" pos="0 0 {P.BOOM_LEN/2}" mass="0.15"
              rgba="0.6 0.62 0.65 1" contype="0" conaffinity="0"/>
        <body name="roll" pos="0 0 {P.BOOM_LEN}">
          <geom name="roll" type="cylinder" size="0.025 {P.PANEL_W/2}" euler="0 90 0" mass="{P.M_TUBE_ARM - 0.15}"
                rgba="0.85 0.85 0.85 1" contype="0" conaffinity="0"/>{panels}
        </body>
      </body>
{''.join(wheels)}
    </body>
  </worldbody>
  <actuator>
{motors}
    <position name="boom_act" joint="boom" kp="30" kv="1.5" ctrlrange="0 1.5708" forcerange="{-P.BOOM_MAX_TORQUE:.3f} {P.BOOM_MAX_TORQUE:.3f}"/>
  </actuator>
  <sensor>
    <jointvel name="enc_fl" joint="wheel_fl"/>
    <jointvel name="enc_fr" joint="wheel_fr"/>
    <jointvel name="enc_rl" joint="wheel_rl"/>
    <jointvel name="enc_rr" joint="wheel_rr"/>
    <accelerometer name="accel" site="imu"/>
    <gyro name="gyro" site="imu"/>
    <framepos name="gnss" objtype="site" objname="gnss"/>
    <framequat name="quat" objtype="xbody" objname="chassis"/>
    <jointpos name="boom_pot" joint="boom"/>
  </sensor>
</mujoco>
"""


def build_props(xml: str) -> str:
    """Same rover/field plus the NVIDIA SimReady props (fence, yard, crates; another agent's assets/simready/).
    Adds a ground plane (props.xml has none) under the heightfield so props outside the field rest on something."""
    inc = '  <include file="../../assets/simready/mjcf/props.xml"/>\n'
    xml = xml.replace("<worldbody>", '<worldbody>\n    <geom name="outer_ground" type="plane" size="20 20 0.1" pos="0 0 -0.002" '
                      'rgba="0.25 0.2 0.14 1" contype="1" conaffinity="1"/>', 1)
    return xml.replace("  <worldbody>", inc + "  <worldbody>", 1)


if __name__ == "__main__":
    xml = build()
    OUT.write_text(xml)
    props_src = pathlib.Path(__file__).resolve().parents[1] / "assets" / "simready" / "mjcf" / "props.xml"
    if props_src.exists():
        (OUT.parent / "rover_props.xml").write_text(build_props(xml))
        print("wrote rover_props.xml (SimReady props included)")
    import mujoco
    m = mujoco.MjModel.from_xml_path(str(OUT))
    d = mujoco.MjData(m)
    mujoco.mj_forward(m, d)
    print("wrote", OUT, "nbody", m.nbody, "total mass %.2f kg" % sum(m.body_mass))
